'use strict';
const fs=require('node:fs');
const assert=require('node:assert/strict');
const {initializeTestEnvironment,assertSucceeds,assertFails}=require('@firebase/rules-unit-testing');
const {doc,collection,getDoc,getDocs,setDoc,updateDoc,writeBatch,serverTimestamp}=require('firebase/firestore');
const projectId='demo-ley-cultura-local',roomCode='A3KL78',hostId='host-ley',studentId='student-ley',otherId='student-other';
let env;
const room=ctx=>doc(ctx.firestore(),'ley_cultura_rooms',roomCode);
const base={gameId:'ley-cultura-v1',hostUid:hostId,organizationId:hostId,title:'Laboratorio de legislación laboral',status:'waiting',round:1,phase:'write',reopenRound:0,reopenToken:0,createdAt:serverTimestamp(),updatedAt:serverTimestamp()};
const candidate=uid=>({uid,name:'Participante '+uid,joinedAt:serverTimestamp(),lastSeenAt:serverTimestamp()});
const assignment=(uid,condition)=>({uid,condition,assignedAt:serverTimestamp()});
const answer=(uid,round,values,revision=1,createdAt=serverTimestamp(),reopenToken=0)=>({uid,round,answer:values,durationMs:2350,revision,reopenToken,createdAt,submittedAt:serverTimestamp()});
const step1={choice:'later',microtask:''};
const step4={words:['Claridad','Acompañamiento','Continuidad','Información'],text:'Los contratos continúan de acuerdo con la legislación aplicable.',initial:'Con el cambio, los contratos de trabajo continúan vigentes.'};
async function run(){
 env=await initializeTestEnvironment({projectId,firestore:{rules:fs.readFileSync('firestore.rules','utf8'),host:'127.0.0.1',port:8080}});
 const host=env.authenticatedContext(hostId,{facilitator:true});
 const student=env.authenticatedContext(studentId,{firebase:{sign_in_provider:'anonymous'}});
 const other=env.authenticatedContext(otherId,{firebase:{sign_in_provider:'anonymous'}});
 const nonHost=env.authenticatedContext('host-other',{facilitator:true});
 await assertSucceeds(setDoc(room(host),base));
 await assertSucceeds(getDoc(room(student)));
 await assertFails(updateDoc(room(student),{round:4}));
 await assertFails(updateDoc(room(nonHost),{round:4}));
 console.log('PASS: creación del anfitrión y control de avances protegido');
 const path=(ctx,coll,id)=>doc(ctx.firestore(),'ley_cultura_rooms',roomCode,coll,id);
 await assertSucceeds(setDoc(path(student,'participants',studentId),candidate(studentId)));
 await assertSucceeds(setDoc(path(other,'participants',otherId),candidate(otherId)));
 await assertFails(getDoc(path(student,'participants',otherId)));
 await assertFails(getDocs(collection(student.firestore(),'ley_cultura_rooms',roomCode,'participants')));
 await assertSucceeds(getDocs(collection(host.firestore(),'ley_cultura_rooms',roomCode,'participants')));
 console.log('PASS: estudiantes no ven nombres ni pueden enumerar participantes');
 await assertFails(setDoc(path(student,'assignments',studentId),assignment(studentId,'A')));
 await assertSucceeds(setDoc(path(host,'assignments',studentId),assignment(studentId,'A')));
 await assertSucceeds(setDoc(path(host,'assignments',otherId),assignment(otherId,'B')));
 await assertFails(getDoc(path(student,'assignments',otherId)));
 await assertSucceeds(getDoc(path(student,'assignments',studentId)));
 await assertSucceeds(updateDoc(room(host),{status:'active',updatedAt:serverTimestamp()}));
 console.log('PASS: las condiciones son asignadas únicamente por facilitador');
 const ownAnswer=path(student,'responses',studentId+'_1'),otherAnswer=path(other,'responses',otherId+'_1');
 const batch=writeBatch(student.firestore());
 batch.set(ownAnswer,answer(studentId,1,step1));
 batch.set(path(student,'response_events',studentId+'_1_123456_100'),{uid:studentId,answerId:studentId+'_1',round:1,answer:step1,durationMs:2350,revision:1,recordedAt:serverTimestamp()});
 await assertSucceeds(batch.commit());
 await assertFails(getDoc(path(other,'responses',studentId+'_1')));
 await assertFails(getDocs(collection(student.firestore(),'ley_cultura_rooms',roomCode,'responses')));
 await assertSucceeds(getDocs(collection(host.firestore(),'ley_cultura_rooms',roomCode,'responses')));
 await assertFails(setDoc(otherAnswer,answer('different-user',1,step1)));
 console.log('PASS: respuestas nominales privadas y escritura vinculada al UID');
 const previous=await getDoc(ownAnswer);
 await assertSucceeds(updateDoc(room(host),{reopenRound:1,reopenToken:1,updatedAt:serverTimestamp()}));
 const batch2=writeBatch(student.firestore());
 batch2.set(ownAnswer,answer(studentId,1,{choice:'continue',microtask:'Organizar las prioridades de mañana'},2,previous.data().createdAt,1));
 batch2.set(path(student,'response_events',studentId+'_1_123457_100'),{uid:studentId,answerId:studentId+'_1',round:1,answer:{choice:'continue',microtask:'Organizar las prioridades de mañana'},durationMs:2350,revision:2,recordedAt:serverTimestamp()});
 await assertSucceeds(batch2.commit());
 await assertFails(getDoc(path(student,'response_events',studentId+'_1_123456_100')));
 console.log('PASS: revisiones guardadas como eventos inmutables');
 await assertSucceeds(updateDoc(room(host),{round:4,phase:'write',updatedAt:serverTimestamp()}));
 const own4=path(student,'responses',studentId+'_4'),other4=path(other,'responses',otherId+'_4');
 await assertSucceeds(setDoc(own4,answer(studentId,4,step4)));
 await assertSucceeds(setDoc(other4,answer(otherId,4,step4)));
 await assertSucceeds(setDoc(path(host,'peer_assignments',studentId),{recipientUid:studentId,sourceUid:otherId,message:step4.text,assignedAt:serverTimestamp()}));
 await assertFails(setDoc(path(host,'peer_assignments',otherId),{recipientUid:otherId,sourceUid:otherId,message:step4.text,assignedAt:serverTimestamp()}));
 await assertSucceeds(updateDoc(room(host),{phase:'review',updatedAt:serverTimestamp()}));
 await assertSucceeds(setDoc(path(student,'perceptions',studentId),{uid:studentId,sourceUid:otherId,perception:'trust',durationMs:1900,submittedAt:serverTimestamp()}));
 await assertFails(getDoc(path(other,'perceptions',studentId)));
 await assertFails(setDoc(path(student,'perceptions',otherId),{uid:otherId,sourceUid:otherId,perception:'pressure',durationMs:1900,submittedAt:serverTimestamp()}));
 console.log('PASS: valoración anónima sin autoevaluación y con permisos individuales');
 console.log('Pruebas de La ley y la cultura completas.');
}
run().catch(err=>{console.error('FAIL',err);process.exitCode=1;}).finally(async()=>{if(env)await env.cleanup();});